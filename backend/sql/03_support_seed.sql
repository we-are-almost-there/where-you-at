    --       나머지 13곳은 금액을 못 찾아 기본 10만으로 둔다. 둘 다 "확인해서 이 값"이
    --       아니라 "아직 확인 못 함"이다 — 지자체 공고로 한 번 훑을 것.
    --
    -- ── 여행유형·인원은 싣지 않는다 (의도한 선택) ──
    --
    -- 공고는 여행유형(가족·개인·단체·청년)과 인원에 따라 환급률과 상한이 갈린다.
    -- 최소 소비도 '1인당'으로 적은 곳이 있어 인원만큼 올라간다. 그런데 그 값들이
    -- 다시 지자체마다 달라서(통합 안내도 '지자체마다 상이' 단서를 단다), 유형 축과
    -- 지역 축이 곱해진다. 여기 구체적인 금액을 적어 두면 그 자체가 틀린 근거가 된다.
