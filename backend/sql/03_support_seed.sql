    --   최소 소비가 적혀 있고 10만이 아닌 곳
    --     화천 7만 — 아래 override에 있다
    --   통합 안내에 금액 문구가 없는 곳 (18곳 — 위 7곳과 합쳐 25곳 전부)
    --     고흥·강진·해남·영암·영광·완도·제천·서천·안동·장흥·밀양·남해·하동·거창·
    --     합천·영월·평창·고창
    --     → 통합 안내가 지자체 공고를 다 옮기지 않는다. 금액은 지자체 공고에 따로 있다.
