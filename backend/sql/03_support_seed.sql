    --
    -- 목록에 없으면 기본 10만이 걸린다. 빠뜨려도 오류가 나지 않고 그 지역만 조용히
    -- 10만 기준으로 계산된다 — 실제로는 받을 수 있는 금액이 0원으로 나온다.
    -- 그래서 "확인했고 기본값이 맞다"와 "확인 안 했다"를 아래에 구분해 적어 둔다.
    --
    -- 2026-09-21 통합 안내(korean.visitkorea.or.kr/dgtourcard/tour50.do) 확인:
