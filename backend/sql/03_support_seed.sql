    --       있지만, 지자체 공고에는 '여행기간 내 1인당 최소 5만원 이상 결제시 환급 대상
    --       (소비 인정 하한액)'이 따로 있다. 상한과 하한이 똑같이 5만원이라 통합 안내만
    --       보면 상한을 하한으로 착각하기 쉽다 — 아래 제천 5만은 하한이 맞다.
    --
    --       이 18곳 중 강진·해남·영암·제천·합천 5곳은 아래 override에 값이 있는데,
