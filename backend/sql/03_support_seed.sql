    -- 담으려면 support.max_amount와 refund_rule.refund_value를 유형별로 쪼개고
    -- 지역 override와 곱한 뒤, 요청에도 유형과 인원을 받아야 한다. 적재 비용이
    -- 얻는 것보다 커서 개인 1인 기준만 싣기로 했다.
    --
    -- 대가는 양방향이다. 더 받을 수 있는 유형은 적게 나오고, '1인당' 최소 소비인
    -- 지역은 여러 명이 갈 때 문턱이 낮게 잡혀 대상이 아닌데도 금액이 나온다.
    -- 그래서 이 값은 '예상'이고, 화면도 지자체 확인을 함께 안내한다.
    ('대한민국 반값여행', '전체', 100000, null, null, true, 50, true,
