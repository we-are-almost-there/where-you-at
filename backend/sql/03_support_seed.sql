-- 2. refund_rule (환급/할인 규칙)
--   반값여행: 정률 50% (환급)
--   디지털 관광주민증: 현장 할인형
--   숙박세일 페스타: 1박/연박 + 금액 구간 별 할인
--    - min_spend = 할인 적용 최소 결제액(구간 하한)
--    - min/max_nights = 숙박 일수 조건 (1박: 1~1, 연박: 2~제한없음)
--    - cap_at_spend = true면 환급액이 실제 지출액을 넘지 못함.

