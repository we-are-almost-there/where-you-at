-- 04_help_seed.sql
-- 고객지원 도메인 데이터 적재 (기능 담당자 문구 확인 완료 2026-09-15)
-- 공지·FAQ 문구는 각 기능 담당자 확인을 받았다. 기능이 바뀌어 문구를 고치면 이 파일을 수정한 뒤
-- 공용 DB에 다시 실행하고, 목 데이터(frontend/src/features/help/helpMock.ts)의 첫 공지도 함께 고친다.
-- 여러 번 실행해도 중복되지 않는다 (아래 "재실행").
-- 대상: notice / faq_category / faq
-- 실행: backend/ 에서  python -m scripts.seed_help  (execute_sql_file 로 이 파일 실행)
--   python scripts/seed_help.py 로 실행하면 scripts 폴더만 모듈 경로에 들어가 app 패키지를 찾지 못한다.
--
-- 문구 원칙
--   코드와 푸터에서 확인되는 동작만 적는다. 버튼·메뉴 이름은 화면 표기와 맞춘다.
--   본문은 제한된 마크다운이다 (01_schema.sql 고객지원 섹션 참고).
--     문단은 빈 줄로 나누고, 목록은 "- ", 굵게는 "**", 링크는 "[글자](주소)"로 쓴다.
--     하위 목록은 "- " 앞을 두 칸 들여쓴다 ("  - "). 한 단계까지만 쓴다.
--     줄바꿈 한 번은 공백으로 이어지므로 목록이 아니면 줄을 나눌 때 빈 줄을 넣는다.
--   줄바꿈은 E'' 문자열 안의 \n으로 넣는다. 파일 줄끝이 CRLF로 바뀌어도
--   DB에 CR 문자가 섞이지 않게 하려는 것이다.
--   문장 안의 따옴표는 SQL 따옴표와 겹치지 않게 ‘ ’를 쓴다.
--
-- 재실행
--   notice: 제목이 같은 행이 있으면 내용·고정 여부만 고치고, 없을 때만 넣는다. id와 게시일이 유지된다 (1번 주석).
--   faq: 값 목록(v)을 한 곳에만 두고, 같은 질문의 기존 행을 지운 뒤 다시 넣는다.
--     FAQ는 id를 화면 주소에 쓰지 않아 다시 넣어 id가 바뀌어도 된다.
--     삭제용 목록을 따로 두면 문구를 고칠 때 한쪽만 바뀌어 중복 행이 생긴다.
--   faq_category: 지우지 않고 이름이 같으면 순서만 갱신한다. FAQ가 참조 중인 카테고리는
--     삭제가 막히고(on delete restrict), 콘솔에서 추가한 FAQ의 카테고리를 끊지 않기 위해서다.
--   콘솔에서 새로 추가한 행은 목록에 없으므로 지워지지 않는다. 다만 이 파일에 있는 행을
--   콘솔에서 고쳤다면 재실행 시 이 파일 내용으로 되돌아간다. 카테고리 이름을 콘솔에서 바꿨다면
--   재실행 시 이 파일의 이름으로 카테고리가 하나 더 생기니, 이 파일의 이름도 같이 고칠 것.
